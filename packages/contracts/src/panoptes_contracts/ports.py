"""Boundaries implemented by workers, never by the management backend."""

from typing import Protocol
from uuid import UUID

from .extraction import ExtractionJob, ExtractionResult, HtmlSnapshot, LayerOutcome
from .llm import LlmInteraction
from .routines import RoutineDefinition


class Extractor(Protocol):
    async def __call__(self, job: ExtractionJob) -> LayerOutcome: ...


class SnapshotStore(Protocol):
    async def put(self, snapshot: HtmlSnapshot, html: bytes) -> None: ...
    async def read(self, snapshot_id: UUID) -> bytes: ...


class JobQueue(Protocol):
    async def claim(
        self, worker_id: str, lease_seconds: int
    ) -> ExtractionJob | None: ...
    async def renew(self, job_id: UUID, worker_id: str, lease_seconds: int) -> None: ...
    async def complete(self, worker_id: str, result: ExtractionResult) -> None: ...


class InteractionLedger(Protocol):
    async def reserve(self, job_id: UUID, ceiling_usd: str) -> UUID: ...
    async def record(self, interaction: LlmInteraction) -> None: ...
    async def reconcile(self, interaction_id: UUID) -> None: ...


class RoutineRepository(Protocol):
    async def read(self, public_id: UUID) -> RoutineDefinition | None: ...
    async def list(
        self, cursor: UUID | None, limit: int
    ) -> tuple[RoutineDefinition, ...]: ...
    async def insert_version(self, routine: RoutineDefinition) -> None: ...
    async def set_enabled(self, public_id: UUID, enabled: bool) -> None: ...
